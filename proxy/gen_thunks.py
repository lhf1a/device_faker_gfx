#!/usr/bin/env python3
"""Generate AArch64 BTI-safe tail-call thunk assembly & symbol tables for EGL and GLESv2 proxies."""
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parent


def extract_exported_funcs(readelf: Path, lib_path: Path, prefix: str, exclude: set[str]) -> list[str]:
    out = subprocess.check_output([str(readelf), '--dyn-syms', str(lib_path)], text=True)
    syms = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 8 and parts[3] == 'FUNC' and parts[6] != 'UND':
            name = parts[7].split('@', 1)[0]
            if name.startswith(prefix) and name not in exclude:
                syms.add(name)
    return sorted(syms)


def write_pair(tag: str, syms: list[str], out_dir: Path) -> None:
    inc_path = out_dir / f'df_{tag}_syms.inc'
    asm_path = out_dir / f'df_{tag}_thunks.S'

    inc_lines = [
        f'/* Auto-generated by proxy/gen_thunks.py ({len(syms)} symbols). Do not edit by hand. */',
        f'#define DF_{tag.upper()}_SYM_COUNT {len(syms)}',
        f'static const char *const g_df_{tag}_sym_names[DF_{tag.upper()}_SYM_COUNT] = {{',
    ]
    for s in syms:
        inc_lines.append(f'    "{s}",')
    inc_lines.append('};')
    inc_path.write_text('\n'.join(inc_lines) + '\n', encoding='utf-8')

    ptrs_sym = f'g_df_{tag}_real_ptrs'
    resolver_sym = f'df_{tag}_resolve_slot'
    helper_sym = f'df_{tag}_lazy_jump'

    asm_lines = [
        f'/* Auto-generated by proxy/gen_thunks.py ({len(syms)} AArch64 BTI-safe tail-call thunks). */',
        '.text',
        '.balign 16',
        f'.type {helper_sym}, %function',
        f'{helper_sym}:',
        '    stp x29, x30, [sp, #-224]!',
        '    mov x29, sp',
        '    stp x0, x1, [sp, #16]',
        '    stp x2, x3, [sp, #32]',
        '    stp x4, x5, [sp, #48]',
        '    stp x6, x7, [sp, #64]',
        '    str x8, [sp, #80]',
        '    stp q0, q1, [sp, #96]',
        '    stp q2, q3, [sp, #128]',
        '    stp q4, q5, [sp, #160]',
        '    stp q6, q7, [sp, #192]',
        '    mov w0, w16',
        f'    bl  {resolver_sym}',
        '    mov x16, x0',
        '    ldp q6, q7, [sp, #192]',
        '    ldp q4, q5, [sp, #160]',
        '    ldp q2, q3, [sp, #128]',
        '    ldp q0, q1, [sp, #96]',
        '    ldr x8, [sp, #80]',
        '    ldp x6, x7, [sp, #64]',
        '    ldp x4, x5, [sp, #48]',
        '    ldp x2, x3, [sp, #32]',
        '    ldp x0, x1, [sp, #16]',
        '    ldp x29, x30, [sp], #224',
        '    cbz x16, 1f',
        '    br  x16',
        '1:',
        '    mov x0, #0',
        '    ret',
        f'.size {helper_sym}, . - {helper_sym}',
        '',
    ]

    for idx, sym in enumerate(syms):
        off = idx * 8
        asm_lines.extend([
            '.balign 4',
            f'.globl {sym}',
            f'.type {sym}, %function',
            f'{sym}:',
            '    hint #36',
            f'    adrp x16, {ptrs_sym}',
            f'    add  x16, x16, :lo12:{ptrs_sym}',
            f'    ldr  x16, [x16, #{off}]',
            f'    cbz  x16, .Llazy_{tag}_{idx}',
            '    br   x16',
            f'.Llazy_{tag}_{idx}:',
            f'    mov  w16, #{idx}',
            f'    b    {helper_sym}',
            f'.size {sym}, . - {sym}',
        ])

    asm_lines.extend([
        '',
        '.section .note.GNU-stack,"",%progbits',
        '',
    ])
    asm_path.write_text('\n'.join(asm_lines), encoding='utf-8')
    print(f'Generated {inc_path.name} and {asm_path.name} ({len(syms)} symbols)')


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit('Usage: gen_thunks.py <llvm-readelf> <ndk-api31-lib-dir>')
    readelf = Path(sys.argv[1])
    lib_dir = Path(sys.argv[2])

    egl_syms = extract_exported_funcs(readelf, lib_dir / 'libEGL.so', 'egl', {'eglGetProcAddress'})
    gles_syms = extract_exported_funcs(readelf, lib_dir / 'libGLESv3.so', 'gl', {'glGetString'})

    write_pair('egl', egl_syms, ROOT)
    write_pair('gles', gles_syms, ROOT)


if __name__ == '__main__':
    main()
